// Writes dist/bc-theme.css from the compiled token values and copies fonts and logo next to it,
// so the values of the theme exist in one place only.
import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { lightTheme, darkTheme } from '../dist/index.js';

const distFolder = fileURLToPath(new URL('../dist/', import.meta.url));
const assetsFolder = fileURLToPath(new URL('../assets/', import.meta.url));

const declarations = (theme) => Object.entries(theme).map(([name, value]) => `  ${name}: ${value};`).join('\n');

const fontFaces = [
  ['Regular', 400, 'normal'],
  ['Bold', 700, 'normal'],
  ['Italic', 400, 'italic'],
  ['BoldItalic', 700, 'italic'],
].map(([file, weight, style]) => `@font-face {
  font-family: "Carlito";
  src: url("./fonts/Carlito-${file}.ttf") format("truetype");
  font-weight: ${weight};
  font-style: ${style};
  font-display: swap;
}`).join('\n');

const css = `/* Generated by scripts/build-css.mjs from src/tokens.ts. Do not edit. */
${fontFaces}

:root {
${declarations(lightTheme)}
}

/* The system setting decides, unless the page pins a theme with data-theme. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${declarations(darkTheme).replace(/^/gm, '  ')}
  }
}

:root[data-theme="dark"] {
${declarations(darkTheme)}
}

html, body {
  margin: 0;
  background: var(--bc-color-background);
  color: var(--bc-color-text);
  font-family: var(--bc-font-family);
  font-size: var(--bc-font-size-body);
  -webkit-font-smoothing: antialiased;
}
`;

mkdirSync(distFolder, { recursive: true });
writeFileSync(`${distFolder}bc-theme.css`, css);
cpSync(`${assetsFolder}fonts`, `${distFolder}fonts`, { recursive: true });
cpSync(`${assetsFolder}logo`, `${distFolder}logo`, { recursive: true });
